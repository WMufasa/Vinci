// Turns scripts/drafts.json into migrations/0004_rework_draft_questions.sql. Questions load with status 'draft' so they are never published
// until approved: wrangler d1 execute vinci --remote --command "UPDATE questions SET status='live' WHERE id IN ('semis','visatx')"
const fs = require('fs');
const drafts = JSON.parse(fs.readFileSync('scripts/drafts.json', 'utf8'));
const s = (v) => v == null ? 'NULL' : "'" + String(v).replace(/'/g, "''") + "'";
const ids = new Set();
// Replaces the unapproved drafts that 0003 loaded. Only 'draft' rows are removed, so approved (live) questions are never touched.
let out = '-- Generated by scripts/make-drafts-sql.js from scripts/drafts.json. Replaces the unapproved drafts from 0003 with the reworked set.\nDELETE FROM questions WHERE status = \'draft\';\n';
for (const q of drafts) {
  if (ids.has(q.id)) throw new Error('duplicate id ' + q.id);
  ids.add(q.id);
  if (!(q.answer > 0) || !q.src || !q.src.url || !q.asof) throw new Error('incomplete: ' + q.id);
  out += 'INSERT INTO questions (id, topic, text, unit, answer, grp, napkin, note, source_label, source_url, as_of, status) VALUES (' +
    [s(q.id), s(q.topic), s(q.q), s(q.unit), String(q.answer), s(q.group), s(q.napkin), s(q.note), s(q.src.label), s(q.src.url), s(q.asof), "'draft'"].join(', ') + ');\n';
}
fs.writeFileSync('migrations/0004_rework_draft_questions.sql', out);
console.log(drafts.length + ' drafts');
