// One-off: extracts the original 12-question bank from vinci_html.html and writes migrations/0002_seed.sql.
const fs = require('fs');
const lines = fs.readFileSync('vinci_html.html', 'utf8').split('\n');
const Q = new Function(lines.slice(207, 257).join('\n').replace('var Q =', 'return') )();
const s = (v) => v == null ? 'NULL' : "'" + String(v).replace(/'/g, "''") + "'";
let out = '-- Generated by scripts/make-seed.js from the original vinci.html question bank.\n';
for (const q of Q) {
  out += 'INSERT INTO questions (id, topic, text, unit, answer, grp, napkin, note, source_label, source_url, as_of, status) VALUES (' +
    [s(q.id), s(q.topic), s(q.q), s(q.unit), String(q.answer), s(q.group), s(q.napkin), s(q.note), s(q.src.label), s(q.src.url), s(q.asof), "'live'"].join(', ') + ');\n';
}
fs.writeFileSync('migrations/0002_seed.sql', out);
console.log(Q.length + ' questions');
